-- 租户元数据表（一村/一合作社一租户）
CREATE TABLE IF NOT EXISTS t_tenant (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   VARCHAR(64)  NOT NULL,
    name        VARCHAR(128) NOT NULL,
    region      VARCHAR(255),
    status      VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_t_tenant_id UNIQUE (tenant_id)
);

COMMENT ON TABLE  t_tenant           IS '多租户元数据（一村/一合作社一租户）';
COMMENT ON COLUMN t_tenant.status    IS '状态：ACTIVE 启用 / DISABLED 停用';

-- 用户/账号表（农户 / 合作社 / 村委，按租户隔离）
CREATE TABLE IF NOT EXISTS t_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id     VARCHAR(64)  NOT NULL,
    username      VARCHAR(64)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    display_name  VARCHAR(64)  NOT NULL,
    role          VARCHAR(32)  NOT NULL,
    phone         VARCHAR(20),
    status        VARCHAR(16)  NOT NULL DEFAULT 'ACTIVE',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_t_user_username UNIQUE (username)
);

CREATE INDEX IF NOT EXISTS idx_t_user_tenant
    ON t_user (tenant_id);

COMMENT ON TABLE  t_user                IS '用户/账号（农户/合作社/村委，按租户隔离）';
COMMENT ON COLUMN t_user.password_hash  IS 'PBKDF2WithHmacSHA256 密码哈希';
COMMENT ON COLUMN t_user.role           IS '角色：FARMER/COOPERATIVE/VILLAGE';
COMMENT ON COLUMN t_user.status         IS '状态：ACTIVE 启用 / DISABLED 停用';
